-- Stillspace tables for Postgres (Supabase, online version, D-47). Same columns as SQLite.
-- Created automatically on start-up; safe to run every time.
CREATE TABLE IF NOT EXISTS participants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL,
    dob TEXT NULL,
    preferred_strategy TEXT DEFAULT 'Automatic',
    setup_done INTEGER DEFAULT 0,
    demo_day_offset INTEGER DEFAULT 0,
    age_group TEXT NULL,
    guardian_consent INTEGER DEFAULT 0,
    consent_at TEXT NULL,
    issued INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS checkins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id INTEGER NOT NULL REFERENCES participants(id),
    type TEXT NOT NULL,
    answers_json TEXT NOT NULL,
    phq_total INTEGER NULL,
    phq_band TEXT NULL,
    phq_complete INTEGER DEFAULT 0,
    item9_flag INTEGER DEFAULT 0,
    session_id INTEGER NULL,
    local_date TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id INTEGER NOT NULL REFERENCES participants(id),
    started_at TEXT NOT NULL,
    ended_at TEXT NULL,
    chat_seconds INTEGER NULL
);
CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id),
    role TEXT NOT NULL,
    text TEXT NOT NULL,
    requested_strategy TEXT NULL,
    classified_strategy TEXT NULL,
    used_strategy TEXT NULL,
    meta_json TEXT NULL,
    safety_flag TEXT DEFAULT 'none',
    source TEXT NULL,
    model TEXT NULL,
    latency_ms INTEGER NULL,
    created_at TEXT NOT NULL
);
-- Sign-in tokens (D-60): only a SHA-256 hash of each token is stored.
CREATE TABLE IF NOT EXISTS auth_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id INTEGER NOT NULL REFERENCES participants(id),
    token_hash TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
-- Columns added after the first online version: databases created earlier get them here.
ALTER TABLE participants ADD COLUMN IF NOT EXISTS age_group TEXT NULL;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS guardian_consent INTEGER DEFAULT 0;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS consent_at TEXT NULL;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS issued INTEGER DEFAULT 0;
-- Supabase publishes tables in the "public" schema through its Data API. Row Level
-- Security with NO policies blocks that API completely; only this app's own
-- database connection (the table owner) can read and write the data.
ALTER TABLE participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE checkins ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_tokens ENABLE ROW LEVEL SECURITY;
